#!/usr/bin/env node
// Regenerates the vocabulary embedded in the grammar plugin from the REAL
// component registries, so the plugin can never drift from what the runtime
// actually accepts (a hand-copied table would be wrong the first time someone
// adds a Quark modifier).
//
//   node tools/generate-vocabulary.js          rewrite the embedded block
//   node tools/generate-vocabulary.js --check  exit 1 if it is out of date
//
// Needs jsdom (a dev dependency): `npm install --no-save jsdom`.

const fs = require("fs");
const path = require("path");
const vm = require("vm");

const RT = path.join(__dirname, "..", "cli", "src", "templates", "cdrca-runtime");
const QUARK_DIR = path.join(RT, "Front-end", "Transpiler-Plugins", "quark");
const RENDERER = path.join(RT, "Front-end", "Renderer.js");
const PLUGIN = path.join(RT, "Back-end", "Transpiler", "Plugins", "grammar", "plugin.js");
const BEGIN = "// <generated:vocabulary>";
const END = "// </generated:vocabulary>";

// `JSDOM` can be passed in by a caller that already has it (the test does);
// the command line loads it from wherever `npm install jsdom` put it.
function extractQuark(JSDOM = require("jsdom").JSDOM) {
  const dom = new JSDOM("<!doctype html><body></body>", { runScripts: "outside-only" });
  const ctx = dom.getInternalVMContext();
  // The same load order the runtime page uses.
  for (const f of ["quark-core.js", "quark-components.js", "quark-templates.js", "quark-families.js", "quark-ui.js"]) {
    new vm.Script(fs.readFileSync(path.join(QUARK_DIR, f), "utf8"), { filename: f }).runInContext(ctx);
  }
  const Q = dom.window.Quark;
  const capabilities = {};
  for (const name of Q.components.list()) {
    const def = Q.components.get(name);
    capabilities[name] = {
      variants: Object.keys(def.variants || {}),
      defaultVariant: def.defaultVariant || null,
      modifiers: Object.keys(def.modifiers || {}),
    };
  }
  return {
    capabilities,
    // Array.from, not .map(): .map() on the jsdom window's array returns an
    // array of THAT window's Array class, which is not deep-equal to ours.
    families: Array.from(Q.families.list(), (f) => f.name),
  };
}

// The animations plugin's `object <name> = <Ctor>(...)` (v2) needs to resolve
// `<Ctor>` to the long runtime path CDRCA's Renderer.js actually exposes
// (`RotatingCube` -> `...exampleProps.RotatingCubeProp`). Rather than typing
// that table by hand (wrong the moment someone adds a prop), extract it
// statically from Renderer.js's own `exampleProps: { ... }` registry object —
// the SAME literal a v2-less project already writes by hand, see
// `templates/starter.cdrca`. Static text extraction, not `vm`-executing the
// file: Renderer.js needs a real THREE.js + canvas + window to even load.
function extractAnimationsProps(rendererSrc = fs.readFileSync(RENDERER, "utf8")) {
  const m = /exampleProps:\s*\{([^}]*)\}/.exec(rendererSrc);
  if (!m) throw new Error(`'exampleProps: { ... }' registry not found in ${RENDERER}`);
  const names = m[1].split(",").map((s) => s.trim()).filter(Boolean);
  if (names.length === 0) throw new Error("exampleProps registry is empty");
  const props = {};
  for (const full of names) {
    if (!/^[A-Za-z_$][\w$]*Prop$/.test(full)) {
      throw new Error(`exampleProps entry '${full}' doesn't end in 'Prop' — the generator's short-name rule (strip 'Prop') doesn't hold for it`);
    }
    props[full.slice(0, -"Prop".length)] = full;
  }
  return props;
}

// `backdrop` has no variants/modifiers/options of its own (section 4.3 of
// the language plan) — it's a fixed shape, not extracted from a live
// registry, so it's spelled out here rather than "discovered".
const ANIMATIONS_CAPABILITIES = {
  backdrop: { variants: [], defaultVariant: null, modifiers: [] },
};

function render(vocab) {
  const body = JSON.stringify(vocab, null, 2).replace(/\n/g, "\n");
  return `${BEGIN}\n// Generated by tools/generate-vocabulary.js from the live component registries.\n// Do not edit by hand — run the generator, or its --check mode in CI.\nconst VOCABULARY = ${body};\n${END}`;
}

function main() {
  const vocab = {
    quark: extractQuark(),
    animations: { capabilities: ANIMATIONS_CAPABILITIES, props: extractAnimationsProps() },
  };
  const src = fs.readFileSync(PLUGIN, "utf8");
  const a = src.indexOf(BEGIN);
  const b = src.indexOf(END);
  if (a === -1 || b === -1) throw new Error(`markers ${BEGIN} / ${END} not found in ${PLUGIN}`);
  const next = src.slice(0, a) + render(vocab) + src.slice(b + END.length);
  if (process.argv.includes("--check")) {
    if (next !== src) {
      console.error("grammar vocabulary is OUT OF DATE — run: node tools/generate-vocabulary.js");
      process.exit(1);
    }
    const n = Object.keys(vocab.quark.capabilities).length;
    const p = Object.keys(vocab.animations.props).length;
    console.log(`grammar vocabulary is up to date (${n} quark components, ${p} animation props).`);
    return;
  }
  fs.writeFileSync(PLUGIN, next);
  console.log(
    `wrote vocabulary: ${Object.keys(vocab.quark.capabilities).length} quark components, ${Object.keys(vocab.animations.props).length} animation props`
  );
}

module.exports = { extractQuark, extractAnimationsProps, ANIMATIONS_CAPABILITIES };
if (require.main === module) main();
