// Resolve an `import "…"` path the way a web page resolves a link:
//   "bg.cdrca" / "./bg.cdrca"   next to the file that says `import`
//   "../shared/x.cdrca"         up from it
//   "/src/bg.cdrca"             from the project root
// Returns the project-root-relative path the runtime's own lookup expects.
// Returns null when the importing file's own path isn't known (a bare
// `transpile()` call with no project) — the caller then passes the text
// through unchanged, which is exactly the legacy `@IMPORT` behaviour.
function resolveImport(spec, currentFile) {
  if (typeof currentFile !== "string") return null;
  const base = spec.startsWith("/") ? [] : currentFile.split("/").slice(0, -1);
  const out = base.slice();
  for (const part of spec.split("/")) {
    if (part === "" || part === ".") continue;
    if (part === "..") {
      if (out.length === 0) return { escapes: true };
      out.pop();
    } else out.push(part);
  }
  return { path: out.join("/") };
}

