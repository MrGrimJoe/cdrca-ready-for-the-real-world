// Edit distance, capped: only "close enough to be a typo" matters.
function distance(a, b) {
  if (Math.abs(a.length - b.length) > 3) return 99;
  const prev = [];
  for (let j = 0; j <= b.length; j++) prev[j] = j;
  for (let i = 1; i <= a.length; i++) {
    let last = prev[0];
    prev[0] = i;
    for (let j = 1; j <= b.length; j++) {
      const tmp = prev[j];
      prev[j] = Math.min(
        prev[j] + 1,
        prev[j - 1] + 1,
        last + (a[i - 1] === b[j - 1] ? 0 : 1)
      );
      last = tmp;
    }
  }
  return prev[b.length];
}

function suggest(word, candidates) {
  const limit = word.length <= 4 ? 1 : 2;
  const scored = [];
  for (const c of candidates) {
    const d = distance(word.toLowerCase(), c.toLowerCase());
    if (d <= limit || c.toLowerCase().startsWith(word.toLowerCase()) || word.toLowerCase().startsWith(c.toLowerCase())) {
      scored.push({ c, d });
    }
  }
  scored.sort((x, y) => x.d - y.d || (x.c < y.c ? -1 : 1));
  return scored.slice(0, 3).map((s) => s.c);
}

function didYouMean(word, candidates) {
  const s = suggest(word, candidates);
  if (s.length === 0) return "";
  return " — did you mean " + s.map((x) => `'${x}'`).join(" or ") + "?";
}

// Where in the file is `offset`? (1-based line and column.)
function locate(lineStarts, offset) {
  let lo = 0;
  let hi = lineStarts.length - 1;
  while (lo < hi) {
    const mid = (lo + hi + 1) >> 1;
    if (lineStarts[mid] <= offset) lo = mid;
    else hi = mid - 1;
  }
  return { line: lo + 1, col: offset - lineStarts[lo] + 1 };
}

class GrammarError extends Error {
  constructor(ctx, offset, length, message, hint) {
    const { line, col } = locate(ctx.lineStarts, offset);
    const start = ctx.lineStarts[line - 1];
    let end = ctx.src.indexOf("\n", start);
    if (end === -1) end = ctx.src.length;
    const lineText = ctx.src.slice(start, end).replace(/\r$/, "");
    const gutter = String(line);
    // Copy tabs so the caret lines up under the source in any terminal.
    const pad = lineText.slice(0, col - 1).replace(/[^\t]/g, " ");
    const carets = "^".repeat(Math.max(1, Math.min(length || 1, lineText.length - (col - 1) || 1)));
    super(
      `line ${line}, column ${col}: ${message}` +
        (hint ? `\n  ${hint}` : "") +
        `\n  ${gutter} | ${lineText}` +
        `\n  ${" ".repeat(gutter.length)} | ${pad}${carets}`
    );
    this.name = "CDRCAGrammarError";
    this.line = line;
    this.column = col;
    this.detail = message;
  }
}

// ---------------------------------------------------------------- lexing

// Split the file into statements. A statement ends at a newline that is not
// inside a string, a comment, or an open ( [ {. Blocks (`JS { ... }`,
// `def PROP X { ... }`) are therefore single statements, and their JavaScript
// bodies are never looked inside.
//
// Returns [{ start, end, commentAt, marker }] where [start, end) is the
// statement text without its newline, `commentAt` is the offset of a trailing
// top-level `//` comment (or -1), and `marker` is true for `!--- ... ---`
// header/scene lines.
function scanUnits(src) {
  const units = [];
  const n = src.length;
  let i = 0;
  while (i <= n) {
    const start = i;
    let j = i;
    let depth = 0;
    let commentAt = -1;
    while (j < n) {
      const c = src[j];
      if (c === "\n") {
        if (depth <= 0) break;
        j++;
        continue;
      }
      if (c === "/" && src[j + 1] === "/") {
        if (depth <= 0 && commentAt === -1) commentAt = j;
        while (j < n && src[j] !== "\n") j++;
        continue;
      }
      if (c === "/" && src[j + 1] === "*") {
        const close = src.indexOf("*/", j + 2);
        j = close === -1 ? n : close + 2;
        continue;
      }
      if (c === '"' || c === "'") {
        // Strings are single-line: an unclosed quote is just a character, so
        // one stray apostrophe can never swallow the rest of the file.
        let k = j + 1;
        while (k < n && src[k] !== c && src[k] !== "\n") {
          if (src[k] === "\\") k++;
          k++;
        }
        if (k < n && src[k] === c) {
          j = k + 1;
          continue;
        }
        j++;
        continue;
      }
      if (c === "`") {
        let k = j + 1;
        while (k < n && src[k] !== "`") {
          if (src[k] === "\\") k++;
          k++;
        }
        j = k < n ? k + 1 : n;
        continue;
      }
      if (c === "{" || c === "[" || c === "(") depth++;
      else if (c === "}" || c === "]" || c === ")") depth--;
      j++;
    }
    const text = src.slice(start, j);
    units.push({ start, end: j, commentAt, marker: /^\s*!-/.test(text) });
    if (j >= n) break;
    i = j + 1;
  }
  return units;
}

// Split on whitespace, but not inside quotes or brackets, so
// `accent=rgb(10, 20, 30)` stays one word. Offsets are into `s`.
function splitWords(s) {
  const out = [];
  const n = s.length;
  let i = 0;
  while (i < n) {
    while (i < n && /\s/.test(s[i])) i++;
    if (i >= n) break;
    const st = i;
    let depth = 0;
    while (i < n) {
      const c = s[i];
      if (c === '"' || c === "'") {
        i++;
        while (i < n && s[i] !== c) {
          if (s[i] === "\\") i++;
          i++;
        }
        i++;
        continue;
      }
      if (c === "(" || c === "[" || c === "{") depth++;
      else if (c === ")" || c === "]" || c === "}") depth--;
      else if (/\s/.test(c) && depth <= 0) break;
      i++;
    }
    out.push({ text: s.slice(st, i), start: st, end: i });
  }
  return out;
}

