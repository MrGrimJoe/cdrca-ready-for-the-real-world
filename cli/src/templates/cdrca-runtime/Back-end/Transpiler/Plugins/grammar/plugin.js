// grammar — the CDRCA statement grammar (v2 syntax), as a built-in plugin.
//
// ⚠️ ARCHITECTURAL DEBT — see docs/design/LANGUAGE-PLAN.md's top section.
//   v2 is the only syntax anyone should write or that any doc shows, but
//   it is NOT yet the only syntax the parser accepts: this plugin rewrites
//   v2 to legacy TEXT, and every other plugin's legacy parsing is still
//   fully intact underneath it. Hand-written legacy syntax still silently
//   compiles today. Converting this to a token-level customRule hook (so
//   legacy text is never produced, and legacy parsing can be deleted from
//   every plugin) is tracked as follow-up work, not done here.
//
// WHAT IT DOES
//   Reads the WHOLE FILE just before it is parsed (the ("before", "parse")
//   hook), finds statements written in the v2 syntax, checks them against the
//   registered vocabulary, and rewrites each one into the equivalent LEGACY
//   statement. Everything else — every legacy statement, every comment,
//   every scene marker, every `JS { }` body — is passed through untouched,
//   byte for byte. The existing parser and plugins then run exactly as they
//   always did.
//
//     @nav navbar glass sticky accent=#10b981     ->  @nav navbar.glass.sticky = #10b981
//     require quark                               ->  @requires quark
//     load quark.components                       ->  @useLib quark.components
//     import "story.cdrca"                        ->  @AddImport "story.cdrca"
//     js { ... }                                  ->  JS { ... }
//
// WHY `import` MEANS `@AddImport` AND NOT `@IMPORT`
//   Both embed another file's scenes, in the same order, with definitions
//   before uses. But a header-position `@IMPORT` only brings in the imported
//   file's OWN content: whatever THAT file imports in turn is silently
//   dropped, so a chain of three files loses the third. `@AddImport` is
//   correct at any depth, so the new keyword uses it. (Legacy `@IMPORT` is
//   left exactly as it was.)
//
// WHY A SOURCE REWRITE, NOT A PARSER CHANGE
//   * Output for equivalent input is identical to the legacy path BY
//     CONSTRUCTION, because it IS the legacy path.
//   * The core tokenizer carries no positions and merges neighbouring
//     one-letter names across whitespace (`x y` becomes `xy`), so a grammar
//     built on its tokens would misread one-letter names and could not point
//     at a column. This plugin lexes the text itself, so errors carry a real
//     line and column and one-letter names are ordinary names.
//   * Nothing in core needs to change.
//
// WHAT COUNTS AS v2 SYNTAX
//   A statement is only ever rewritten (or reported as an error) when its
//   SHAPE cannot be legacy syntax. `@id word` with nothing after it is legal
//   in both and is left alone; `@id word flag flag` has space-separated flags,
//   which no legacy statement has, so it is unambiguously v2 — and only then
//   is an unknown `word` a build error rather than a runtime console warning.
//
// Loaded in the plugin host's sandbox: no require(), no fs. Everything it
// needs is in this file; the vocabulary below is generated from the real
// component registries by tools/generate-vocabulary.js and checked for drift
// by tests/vocabulary.test.js.

